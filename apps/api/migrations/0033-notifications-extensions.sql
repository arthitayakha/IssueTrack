-- 0033: notifications — actor/context/link columns for the bell dropdown.
-- Idempotent on purpose — safe to run more than once.

-- legacy table was created without a serial default on `id`, so every insert failed
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'notifications' AND column_name = 'id'
      AND (is_identity = 'YES' OR column_default IS NOT NULL)
  ) THEN
    ALTER TABLE notifications ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

ALTER TABLE notifications
  ADD COLUMN IF NOT EXISTS actor_id    INTEGER,
  ADD COLUMN IF NOT EXISTS actor_name  VARCHAR(100),
  ADD COLUMN IF NOT EXISTS context     VARCHAR(100),
  ADD COLUMN IF NOT EXISTS link        VARCHAR(255),
  ADD COLUMN IF NOT EXISTS is_archived BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS read_at     TIMESTAMPTZ;

-- legacy column was `timetz` (time-of-day only, no date) — convert to a real timestamp
ALTER TABLE notifications
  ALTER COLUMN created_at TYPE TIMESTAMPTZ
    USING ((CURRENT_DATE::timestamp + created_at::time)::timestamptz),
  ALTER COLUMN created_at SET DEFAULT now();

-- notification targets are not always an issue (future system notices)
ALTER TABLE notifications
  ALTER COLUMN issue_id DROP NOT NULL;

-- badge/list lookups: WHERE user_id = ? ORDER BY created_at DESC
CREATE INDEX IF NOT EXISTS idx_notifications_user_created
  ON notifications (user_id, created_at DESC);
